function visualizeRetinalResult(img, result, imageName)

figure("Name", imageName, "NumberTitle", "off");

imshow(img);
hold on;

% Optic disc
if isfield(result, "localization") && ...
   isfield(result.localization, "disc")

    disc = result.localization.disc;

    viscircles( ...
        [disc.centerX disc.centerY], ...
        disc.radius, ...
        "Color", "r", ...
        "LineWidth", 2);

end

% Fovea
if isfield(result, "localization") && ...
   isfield(result.localization, "fovea")

    fovea = result.localization.fovea;

    plot( ...
        fovea.centerX, ...
        fovea.centerY, ...
        "b+", ...
        "MarkerSize", 15, ...
        "LineWidth", 3);

end

title( ...
    imageName + ...
    " | Quality: " + result.quality + ...
    " | Stage: " + result.processing_stage);

hold off;

end